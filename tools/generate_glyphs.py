#!/usr/bin/env python3
"""Generate Sources/VexFoundation/Rendering/Glyphs.swift from upstream src/glyphs.ts.

Usage: tools/generate_glyphs.py [UPSTREAM_DIR]   (default: ../vexflow-5.9.0)
"""
import os, re, sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
upstream = sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, '..', 'vexflow-5.9.0')
src = open(os.path.join(upstream, 'src', 'glyphs.ts'), encoding='utf-8').read()

entry = re.compile(r"^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*'((?:\\[^']|[^'\\])*)',\s*$")
comment = re.compile(r"^\s*//\s*(U\+[0-9A-F]+.*)$")

def to_swift(value):
    out = []
    i = 0
    while i < len(value):
        c = value[i]
        if c == '\\':
            n = value[i + 1]
            if n == 'u':
                if value[i + 2] == '{':
                    j = value.index('}', i)
                    out.append('\\u{%s}' % value[i + 3:j].upper()); i = j + 1; continue
                out.append('\\u{%s}' % value[i + 2:i + 6].upper()); i += 6; continue
            if n == '0':
                out.append('\\0'); i += 2; continue
            out.append('\\' + n); i += 2; continue
        out.append(c); i += 1
    return ''.join(out)

lines = []
pending = None
names = []
for line in src.splitlines():
    m = comment.match(line)
    if m:
        pending = m.group(1)
        continue
    m = entry.match(line)
    if m:
        name, value = m.groups()
        if pending:
            lines.append('    /// %s' % pending)
        lines.append('    public static let %s = "%s"' % (name, to_swift(value)))
        names.append(name)
        pending = None

header = '''// VexFoundation - Ported from VexFlow (https://vexflow.com)
// GENERATED by tools/generate_glyphs.py from upstream src/glyphs.ts. Do not edit.
//
// All SMuFL glyphs plus a few others that VexFlow uses. Values are the
// glyph code points as Swift strings. Two SMuFL names start with a digit
// and were renamed upstream: 4stringTabClef => fourStringTabClef,
// 6stringTabClef => sixStringTabClef.

// swiftlint:disable all
public enum Glyphs {
'''
body = '\n'.join(lines)
lookup = '\n'.join('        "%s": %s,' % (n, n) for n in names)
footer = '''
}

extension Glyphs {
    /// Look up a glyph code point by its SMuFL (VexFlow) name.
    public static func code(named name: String) -> String? { byName[name] }

    /// All glyph names mapped to code points.
    public static let byName: [String: String] = [
%s
    ]
}
''' % lookup
out = os.path.join(root, 'Sources', 'VexFoundation', 'Rendering', 'Glyphs.swift')
open(out, 'w', encoding='utf-8').write(header + body + footer)
print('wrote %d glyphs to %s' % (len(names), out))
